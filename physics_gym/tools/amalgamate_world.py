#!/usr/bin/env python3
"""amalgamate_world.py: write physics_world.c, one standalone C file: the physics world (bmath.h, body.h, joint_limits.h,
muscle.h, body.c, room.c, body_x8.c), the tasks and rewards (mref.c, env.c), the controller (../nanotss_blt.c: the
tree-SSM with FFF blocks, ternary weights, blockwise Muon) and the CPU trainer (ppo_tss.c), the same code with the
local #includes inlined. tools/world_demo.c is its main under -DPHYSICS_WORLD_DEMO; -DPHYSICS_ONLY leaves the physics
alone.   python3 tools/amalgamate_world.py   (run again whenever any of them changes)"""
import os, re
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
read = lambda f: open(os.path.join(ROOT, f)).read()
def inline(text, done):
    def sub(m):
        f = m.group(1)
        if f in done: return f"/* ({f}: above) */"
        done.add(f); return f"/* ======== {f} ======== */\n" + inline(read(f), done) + f"\n/* ======== end of {f} ======== */"
    return re.sub(r'#include "([^"]+)"[^\n]*', sub, text)
HEAD = '''/* physics_world.c: the physics gym in one file: the world, the tasks and rewards, the tree-SSM controller and its CPU
 * trainer. Generated by tools/amalgamate_world.py from bmath.h, body.h, joint_limits.h, muscle.h, body.c, room.c,
 * body_x8.c, mref.c, env.c, ../nanotss_blt.c and ppo_tss.c; edit those, then run it again.
 *
 * The world: a 14-body character (45 kg; pelvis, spine, chest, head, upper and lower arms, thighs, shins, feet as boxes)
 * under XPBD (Mueller et al. 2020): ball joints with the motion capture's joint ranges as ligaments, a muscle at every
 * joint driving it toward a target rotation within its strength and how fast its torque can rise, gravity, floor and
 * room contacts with static and Coulomb friction, the legs colliding with each other, hand grips on holds and ledges,
 * rooms of static boxes (room.json, from room.py; banks of them) with a nav grid for path finding; 8 worlds stepped at
 * once in vector lanes (body_x8.c). The same arithmetic as the GPU build and body.js (fdlibm's sin, cos, exp, log,
 * atan2, below), so with contraction off it gives the same bits.
 * The tasks (env.c): balance, imitation of a clip, crawl, get up, walking to goals over a room bank (the path helper,
 * the look inputs), tracking a clip set (get-ups from real falls; jump courses in a room), with their observations
 * and rewards. The controller (nanotss_blt.c): an SSM-tree and FFF stack with ternary weights and int8 activations
 * (AVX-512 kernels), run as a recurrent policy one control step at a time; trained by PPO (ppo_tss.c) with the
 * stack's own update (clipping, Adam, blockwise Muon), Adam for the input projection and action head, an MLP critic.
 * Its .tss / .head files are the GPU trainer's (gpu/ppo_gpu.py) and the viewer's (tools/tss2json.py).
 *
 *   cc -O3 -march=native -fopenmp -ffp-contract=off -o gym physics_world.c -lm
 *   ./gym --task balance --seconds 600 --out balance                         train (writes balance.tss, balance.head)
 *   ./gym --task goto --mref cmu_gait.bin --room rooms_nav.json --load aware --assist 0.05 --assist-auto --out goto2
 *   ./gym --task getup_imitate --style cmu_jump.bin:fjump1,fjump2 --room jump_bank_standing.json --load jump_stick --eval 64
 *   cc -O2 -ffp-contract=off -DPHYSICS_WORLD_DEMO -o world physics_world.c -lm && ./world [room.json]   the physics demo
 *   cc -O2 -ffp-contract=off -DPHYSICS_ONLY -c physics_world.c                  the physics alone, as a library
 * (The data files are in the repository's physics_gym/data: clips, room banks, trained policies in data/clean/warm.)
 *
 * The world's essentials:
 *   World W; world_init(&W, 45, 20, 1.0 / 30);       mass (kg), substeps, control step (s)
 *   world_pose(&W, root_x, root_q, rel, root_v);      place her: pelvis position and rotation, each joint's rotation
 *                                                     (child in parent, rest frame; QID = the rest T-pose)
 *   W.target[i] = q;                                  what joint i's muscles pull toward (child in parent)
 *   world_step(&W);                                   advance one control step
 *   W.b[i].x, .q, .v, .w                              each body's centre, rotation, velocity, angular velocity
 *   W.touch[i], W.act[i]                              contact force on each body (N), each joint's muscle activation
 *   room_load("room.json"); room_load_bank(...); support_y(room, x, z, ytop); ray_dist(...); nav_h(...)
 *   W.kp_scale, W.strength, W.limit_k, W.push_*, W.grip_cmd[], W.assist ...           see World in body.h
 * Units: metres, kilograms, seconds; y up, she faces +z, her left is +x.
 *
 * Joint ranges and muscle limits come from the CMU Graphics Lab Motion Capture Database (mocap.cs.cmu.edu; NSF
 * EIA-0196217) through tools/joint_limits.py and tools/muscle_envelope.py.
 */
#include <math.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
'''
done = set()
out = HEAD + inline('#include "body.c"\n', done) + "\n" + inline(read("room.c"), done)
# body_x8.c's file-local helpers (short names: S, V, add, dot, CORNER, ...) get an x8_ prefix here, where they share one
# file with body.c and nanotss_blt.c; the names come from its own static declarations
x8 = sorted(set(re.findall(r'^static(?: inline)?(?: const)? [A-Za-z0-9_]+\s*\**\s*([A-Za-z_][A-Za-z0-9_]*)\s*[\(\[]', read("body_x8.c"), re.M)))
pre = "".join(f"#define {n} x8_{n}\n" for n in x8); post = "".join(f"#undef {n}\n" for n in x8)
out += "\n#ifndef PHYSICS_ONLY\n/* (body_x8.c's local names, prefixed) */\n" + pre + inline('#include "body_x8.c"\n', done) + "\n" + post + inline('#include "mref.c"\n#include "env.c"\n', done)
ppo = read("ppo_tss.c").replace("int main(int argc, char **argv) {", "PPO_MAIN(int argc, char **argv) {", 1)
out += "\n#ifdef PHYSICS_WORLD_DEMO\n#define PPO_MAIN static int ppo_main   /* the demo's main instead */\n#else\n#define PPO_MAIN int main\n#endif\n" + inline(ppo, done) + "\n#endif   /* PHYSICS_ONLY */\n"
out += "\n#ifdef PHYSICS_WORLD_DEMO\n#define PHYSICS_WORLD_DEMO_EMBEDDED\n/* ======== tools/world_demo.c ======== */\n" + read("tools/world_demo.c") + "#endif\n"
open(os.path.join(ROOT, "physics_world.c"), "w").write(out)
print(f"physics_world.c: {out.count(chr(10))} lines")
