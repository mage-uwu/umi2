#!/usr/bin/env python3
"""amalgamate_world.py: write physics_world.c, the physics world (bmath.h, body.h, joint_limits.h, muscle.h, body.c,
room.c) as one standalone C file, the same code with the local #includes inlined; tools/world_demo.c as its main
under -DPHYSICS_WORLD_DEMO.   python3 tools/amalgamate_world.py   (run again whenever the physics changes)"""
import os, re
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
read = lambda f: open(os.path.join(ROOT, f)).read()
def inline(text, done):
    def sub(m):
        f = m.group(1)
        if f in done: return f"/* ({f}: above) */"
        done.add(f); return f"/* ======== {f} ======== */\n" + inline(read(f), done) + f"\n/* ======== end of {f} ======== */"
    return re.sub(r'#include "([^"]+)"[^\n]*', sub, text)
HEAD = '''/* physics_world.c: the physics-gym world in one file. Generated by tools/amalgamate_world.py from bmath.h, body.h,
 * joint_limits.h, muscle.h, body.c and room.c; edit those, then run it again.
 *
 * A 14-body character (45 kg; pelvis, spine, chest, head, upper and lower arms, thighs, shins, feet as boxes) under
 * XPBD (Mueller et al. 2020): ball joints with the motion capture's joint ranges as ligaments, a muscle at every joint
 * driving it toward a target rotation within its strength and how fast its torque can rise, gravity, floor and room
 * contacts with static and Coulomb friction, the legs colliding with each other, hand grips on holds and ledges, and
 * rooms of static boxes (room.json, from room.py) with a nav grid for path finding. The same arithmetic as the GPU
 * build and body.js (sin, cos, exp, log, atan2 from fdlibm, below), so with contraction off it gives the same bits.
 *
 *   cc -O2 -ffp-contract=off -c physics_world.c                         (a library: the API in body.h, below)
 *   cc -O2 -ffp-contract=off -DPHYSICS_WORLD_DEMO -o world physics_world.c -lm && ./world [room.json]   (a demo)
 *
 * The essentials:
 *   World W; world_init(&W, 45, 20, 1.0 / 30);       mass (kg), substeps, control step (s)
 *   world_pose(&W, root_x, root_q, rel, root_v);      place her: pelvis position and rotation, each joint's rotation
 *                                                     (child in parent, rest frame; QID = the rest T-pose)
 *   W.target[i] = q;                                  what joint i's muscles pull toward (child in parent)
 *   world_step(&W);                                   advance one control step
 *   W.b[i].x, .q, .v, .w                              each body's centre, rotation, velocity, angular velocity
 *   W.touch[i], W.act[i]                              contact force on each body (N), each joint's muscle activation
 *   room_load("room.json"); support_y(room, x, z, ytop); ray_dist(...); nav_h(...)   the room and terrain queries
 *   W.kp_scale, W.strength, W.limit_k, W.push_*, W.grip_cmd[], W.assist ...           see World in body.h
 * Units: metres, kilograms, seconds; y up, she faces +z, her left is +x.
 *
 * Joint ranges and muscle limits come from the CMU Graphics Lab Motion Capture Database (mocap.cs.cmu.edu; NSF
 * EIA-0196217) through tools/joint_limits.py and tools/muscle_envelope.py.
 */
#include <math.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
'''
done = set()
out = HEAD + inline('#include "body.c"\n', done) + "\n" + inline(read("room.c"), done)
out += "\n#ifdef PHYSICS_WORLD_DEMO\n#define PHYSICS_WORLD_DEMO_EMBEDDED\n/* ======== tools/world_demo.c ======== */\n" + read("tools/world_demo.c") + "#endif\n"
open(os.path.join(ROOT, "physics_world.c"), "w").write(out)
print(f"physics_world.c: {out.count(chr(10))} lines")
